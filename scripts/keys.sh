#!/usr/bin/env bash
# Generate the signing keys in KEYS_DIR: dev-*, the development keys, with
# `make`; or release-*, the keys that users' machines trust, only when asked.
# NAME-secureboot.key and NAME-secureboot.crt sign systemd-boot and the UKI,
# and shim trusts them once the certificate is enrolled as a MOK. NAME-pcr.key
# signs the UKI's expected PCR 11 values, which the TPM2 key slot is bound to,
# so that each key can be replaced on its own (docs/Design-Security.md). Existing keys are kept: a new one would
# need enrolling again. RSA-2048 is what shim and every TPM2 accept.
# Usage: keys.sh           (called by `make`)
#        keys.sh --release (called by `make release-key`)
set -euo pipefail
: "${KEYS_DIR:?}" "${SIGNING_KEY:?}"

name=dev subject="ShapeBit Development"
if [[ ${1:-} == --release ]]; then
  name=release subject="ShapeBit"
  # `make clean` removes build/.
  case $(realpath -m "$KEYS_DIR")/ in
    "$(realpath -m build)"/*)
      echo "error: keep the release keys outside build/: make release-key KEYS_DIR=<directory>" >&2
      exit 1
      ;;
  esac
elif [[ $SIGNING_KEY != dev ]]; then
  echo "error: $KEYS_DIR/$SIGNING_KEY-secureboot.key or $SIGNING_KEY-pcr.key not found; they are never generated by a build" >&2
  exit 1
fi

mkdir -p "$KEYS_DIR"
umask 077
if [[ ! -f $KEYS_DIR/$name-secureboot.crt ]]; then
  openssl req -quiet -new -x509 -newkey rsa:2048 -nodes -sha256 -days 3650 \
    -subj "/CN=$subject/" -keyout "$KEYS_DIR/$name-secureboot.key" \
    -out "$KEYS_DIR/$name-secureboot.crt"
fi
if [[ ! -f $KEYS_DIR/$name-pcr.key ]]; then
  openssl genpkey -quiet -algorithm RSA -pkeyopt rsa_keygen_bits:2048 -out "$KEYS_DIR/$name-pcr.key"
fi
