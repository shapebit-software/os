#!/usr/bin/env bash
# Generate a signing key in KEYS_DIR: dev.key and dev.crt, the development key,
# with `make`; or release.key and release.crt, the key that users' machines
# trust, only when asked. A key signs systemd-boot, the UKI, and the UKI's
# expected PCR 11 values, and shim trusts it once its certificate is enrolled
# as a MOK. An existing key is kept: a new one would need enrolling again.
# Usage: keys.sh           (called by `make`)
#        keys.sh --release (called by `make release-key`)
set -euo pipefail
: "${KEYS_DIR:?}" "${SIGNING_KEY:?}"

name=dev subject="ShapeBit Development"
if [[ ${1:-} == --release ]]; then
  name=release subject="ShapeBit"
  # `make clean` removes build/.
  case $(realpath -m "$KEYS_DIR")/ in
    "$(realpath -m build)"/*)
      echo "error: keep the release key outside build/: make release-key KEYS_DIR=<directory>" >&2
      exit 1
      ;;
  esac
elif [[ $SIGNING_KEY != dev ]]; then
  echo "error: $KEYS_DIR/$SIGNING_KEY.key not found; it is never generated by a build" >&2
  exit 1
fi

[[ -f $KEYS_DIR/$name.crt ]] && exit 0
mkdir -p "$KEYS_DIR"
(umask 077 && openssl req -quiet -new -x509 -newkey rsa:2048 -nodes -sha256 -days 3650 \
  -subj "/CN=$subject/" -keyout "$KEYS_DIR/$name.key" -out "$KEYS_DIR/$name.crt")
