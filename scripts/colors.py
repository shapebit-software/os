#!/usr/bin/env python3
"""Write the values of the QML module Colors (ColorValues.qml) from the
system's colors, image/rootfs/usr/share/colors/colors.toml, which is where to
change them. The generated file is committed, so the image's tree stays the
installed system; tests/unit/test_colors.py fails when it is out of date.

Usage: colors.py           (called by `make colors`)
       colors.py --check   exit 1 if ColorValues.qml is out of date
"""

import math
import pathlib
import sys
import tomllib

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE = ROOT / "image/rootfs/usr/share/colors/colors.toml"
TARGET = ROOT / "image/rootfs/usr/lib64/qt6/qml/Colors/ColorValues.qml"


def linear(l, c, h):
    """OKLCH as linear sRGB, which may fall outside 0 to 1."""
    a, b = c * math.cos(math.radians(h)), c * math.sin(math.radians(h))
    l_ = (l + 0.3963377774 * a + 0.2158037573 * b) ** 3
    m_ = (l - 0.1055613458 * a - 0.0638541728 * b) ** 3
    s_ = (l - 0.0894841775 * a - 1.2914855480 * b) ** 3
    return (4.0767416621 * l_ - 3.3077115913 * m_ + 0.2309699292 * s_,
            -1.2684380046 * l_ + 2.6097574011 * m_ - 0.3413193965 * s_,
            -0.0041960863 * l_ - 0.7034186147 * m_ + 1.7076147010 * s_)


def oklch(l, c, h):
    """An OKLCH color as "#rrggbb", as Colors.oklch makes it."""
    def channel(x):
        x = min(1, max(0, x))
        return round(255 * (12.92 * x if x <= 0.0031308 else 1.055 * x ** (1 / 2.4) - 0.055))
    return "#" + "".join(f"{channel(x):02x}" for x in linear(l, c, h))


def load(path=SOURCE):
    with open(path, "rb") as file:
        return tomllib.load(file)


def colors(table):
    """Every named color as "#rrggbb"."""
    return {name: value if isinstance(value, str) else oklch(*value["oklch"])
            for name, value in table["colors"].items()}


def roles(table, surface):
    """A set of roles as "#rrggbb", or "#aarrggbb" with an opacity, as Qt writes them."""
    named = colors(table)
    found = {}
    for role, value in table["roles"][surface].items():
        if isinstance(value, str):
            found[role] = named[value]
        else:
            found[role] = f"#{round(value['alpha'] * 255):02x}{named[value['color']][1:]}"
    return found


def qml(table):
    def number(x):
        return repr(float(x)).removesuffix(".0") if float(x).is_integer() else repr(x)

    def numbers(values):
        return "[" + ", ".join(number(x) for x in values) + "]"

    accents = table["accents"]
    lines = [
        "// Generated by scripts/colors.py from /usr/share/colors/colors.toml, the",
        "// system's colors, which say what each is for. Change them there, then run",
        "// `make colors`; Colors.qml builds on these values.",
        "import QtQuick",
        "",
        "QtObject {",
    ]
    lines += [f'    readonly property color {name}: "{value}"' for name, value in colors(table).items()]
    lines += [
        "",
        "    readonly property var pens: [" + ", ".join(f'"{pen}"' for pen in table["pens"]) + "]",
        "",
        "    readonly property var accents: ({",
        ",\n".join(f'        "{name}": {numbers(values)}' for name, values in accents["presets"].items()),
        "    })",
        f'    readonly property string defaultAccent: "{accents["default"]}"',
        f"    readonly property var customAccent: {numbers(accents['custom'])}",
        f"    readonly property var softAccent: {numbers(accents['soft'])}",
        f"    readonly property real inkAccentLightness: {number(accents['ink'])}",
    ]
    for surface in table["roles"]:
        lines += ["", f"    readonly property Roles {surface}: Roles {{"]
        lines += [f'        {role}: "{value}"' for role, value in roles(table, surface).items()]
        lines += ["    }"]
    lines += ["}", ""]
    return "\n".join(lines)


def main(args):
    text = qml(load())
    if args == ["--check"]:
        if TARGET.read_text() != text:
            print(f"{TARGET.relative_to(ROOT)} is out of date: run `make colors`", file=sys.stderr)
            return 1
        return 0
    if args:
        print(__doc__, file=sys.stderr)
        return 2
    TARGET.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
